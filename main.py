# math_utils.py

def add_numbers(a, b):

    return a + b

def multiply_numbers(a, b):

    return a * b

def greet_user(name):

    return f"Hello, {name}! Welcome to VS Code."

def main():

    print(add_numbers(13, 12))

    print(multiply_numbers(4, 5))

    print(greet_user("Achilles David"))

if __name__ == "__main__":

    main()